"""Kaggle notebook outputs of share/kaggle/mk_embed.py -> one shared dataset folder (files are MOVED, not copied).

  vectors/dense-NNNN.npy      fp16 (n, 1024), L2-normalised
  vectors/ids-NNNN.parquet    doc_id[, chunk_idx]: row i of dense-NNNN.npy / sparse-NNNN.parquet
  vectors/sparse-NNNN.parquet doc_id[, chunk_idx], tok (list<int32> bge-m3 token ids), w (list<float32> weights)
  chunks/chunks-NNNN.parquet  the text that was embedded (embed_export.py input), when --chunks is given
  queries.parquet (id, query, text = normalised query), queries_dense.npy, queries_sparse.parquet (id, tok, w)
  README.md, dataset-metadata.json

  python devset/pack_embeddings.py --runs C:/vibiomir/kout/emb512a-s0 C:/vibiomir/kout/emb512a-s1 \
      --chunks C:/vibiomir/kaggle/chunks512a --out C:/vibiomir/share/bgem3-chunks512 --title vibiomir-bgem3-chunks512 --owner gloryvu
"""
import argparse, json, re, shutil
from pathlib import Path
import torch  # noqa: F401  (Windows: torch DLLs before pyarrow)
import numpy as np, pandas as pd, pyarrow.parquet as pq

README = """# {title}

bge-m3 (`BAAI/bge-m3`) **dense + sparse** embeddings of the ViBioMIR {lang} **{what}** from the clean chunker
(commit {chunker}: per-site article isolation, h1 > h2 > h3 heading paths in `title`, tables / captions
kept, boilerplate stripped). {coverage}

## Text that was embedded (chunks and queries alike)
`title + ". " + context` (the heading path, else the page title), then `textprep.normalize` (Unicode **NFC**, curly
quotes -> straight, `|` removed, whitespace collapsed) and `textprep.bm25_normalize` (one Vietnamese tone-mark
placement: hoà -> hòa, khoẻ -> khỏe), so one syllable is one token id in the sparse weights. Max {maxlen} tokens.
Queries: the same normalisation, no prefix (`queries.parquet` keeps the raw `query` and the encoded `text`).

## Files
- `vectors/dense-NNNN.npy`: fp16 `(n, 1024)`, L2-normalised CLS vectors (as `SentenceTransformer("BAAI/bge-m3")`,
  cosine 0.9998 with it on a sample).
- `vectors/ids-NNNN.parquet`: `doc_id`{chunk_col}: row *i* = row *i* of the dense and sparse file with the same number.
- `vectors/sparse-NNNN.parquet`: `doc_id`{chunk_col}, `tok` (list of bge-m3 token ids), `w` (lexical weight per id:
  relu(sparse_linear(h)), max over repeats, special tokens dropped; as FlagEmbedding `BGEM3FlagModel` lexical_weights).
- `queries_dense.npy` / `queries_sparse.parquet` (`id`, `tok`, `w`) / `queries.parquet`: the 1,200 queries, same order.
{chunks_doc}

## Hybrid score (dense + sparse, no BM25 needed)
```python
dense = q_vec @ d_vec                                    # cosine (both normalised)
sparse = sum(qw[t] * dw[t] for t in set(q_tok) & set(d_tok))   # bge-m3 lexical matching
score = dense + 0.3 * sparse                             # bge-m3 paper weights dense 1 : sparse 0.3
```
For top-k over all chunks: dense with a matrix product on GPU; sparse with a scipy CSR matrix (vocab 250,002) and
`Q_csr @ D_csr.T`.

## Usage
```python
import glob, numpy as np, pandas as pd
D = "/kaggle/input/{title}"
V = np.vstack([np.load(f) for f in sorted(glob.glob(f"{{D}}/vectors/dense-*.npy"))])
ids = pd.concat([pd.read_parquet(f) for f in sorted(glob.glob(f"{{D}}/vectors/ids-*.parquet"))], ignore_index=True)
Q = np.load(f"{{D}}/queries_dense.npy"); q = pd.read_parquet(f"{{D}}/queries.parquet")
```
Generated by `share/kaggle/mk_embed.py` (Kaggle) and packed by `devset/pack_embeddings.py`.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", required=True, help="downloaded kernel output dirs")
    ap.add_argument("--chunks", default="", help="embed_export.py folder with the embedded text (moved into chunks/)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--owner", required=True)
    ap.add_argument("--what", default="512-syllable section chunks")
    ap.add_argument("--coverage", default="")
    ap.add_argument("--maxlen", type=int, default=1024)
    ap.add_argument("--lang", choices=["vi", "zh"], default="vi")
    ap.add_argument("--chunker", default="434c29d, Oct 23 2026", help="chunker commit and date for the README")
    ap.add_argument("--start", type=int, default=0, help="first part number (for a later version that adds parts)")
    a = ap.parse_args()
    out = Path(a.out); (out / "vectors").mkdir(parents=True, exist_ok=True)
    k, rows, has_chunk = a.start, 0, False
    for run in map(Path, a.runs):
        parts = sorted({re.sub(r"-(dense\.npy|ids\.parquet|sparse\.parquet)$", "", p.name) for p in run.glob("emb-*-*-*")})
        for pre in parts:
            dn, idf, spf = run / f"{pre}-dense.npy", run / f"{pre}-ids.parquet", run / f"{pre}-sparse.parquet"
            V = np.load(dn, mmap_mode="r"); ids = pd.read_parquet(idf)
            assert V.shape[0] == len(ids), (pre, V.shape, len(ids))
            if spf.exists():
                sk = pq.read_table(spf, columns=list(ids.columns)).to_pandas()
                assert (sk.values == ids.values).all(), f"{pre}: sparse rows not aligned with ids"
            has_chunk = "chunk_idx" in ids.columns
            rows += len(ids); del V
            shutil.move(dn, out / "vectors" / f"dense-{k:04d}.npy")
            shutil.move(idf, out / "vectors" / f"ids-{k:04d}.parquet")
            if spf.exists():
                shutil.move(spf, out / "vectors" / f"sparse-{k:04d}.parquet")
            k += 1
    first = Path(a.runs[0])
    for f in ("queries.parquet", "queries_dense.npy", "queries_sparse.parquet"):
        if (first / f).exists() and not (out / f).exists():
            shutil.copy(first / f, out / f)
    chunks_doc = ""
    if a.chunks:
        (out / "chunks").mkdir(exist_ok=True)
        for p in sorted([*Path(a.chunks).glob("chunks-*.parquet"), *Path(a.chunks).glob("pages-*.parquet")]):
            dst = out / "chunks" / p.name
            i = 0
            while dst.exists():                       # a later version: keep numbering unique
                i += 1; dst = out / "chunks" / f"{p.stem}-v{i}.parquet"
            shutil.move(p, dst)
        pages = any(Path(a.chunks).glob("pages-*.parquet")) or any((out / "chunks").glob("pages-*.parquet"))
        chunks_doc = ("- `chunks/pages-*.parquet`: the embedded pages: `doc_id`, `url`, `text` (h1 + heading lines + chunk texts in "
                      "page order; the text that was embedded, before normalisation)." if pages else
                      "- `chunks/chunks-*.parquet`: the embedded chunks: `doc_id`, `chunk_idx`, `url`, `title` (heading path), "
                      "`context` (**verbatim page text**, for `relevant_chunks`), `token_count`, `method`, `page_title`, `h1`, "
                      "`n_docs_same_text` (>= 20 = boilerplate shared across docs). Join on (`doc_id`, `chunk_idx`).")
    (out / "README.md").write_text(README.format(
        title=a.title, what=a.what, coverage=a.coverage, maxlen=a.maxlen, lang=dict(vi='Vietnamese', zh='Chinese')[a.lang], chunker=a.chunker,
        chunk_col=", `chunk_idx`" if has_chunk else "", chunks_doc=chunks_doc), encoding="utf-8")
    (out / "dataset-metadata.json").write_text(json.dumps({"title": a.title, "id": f"{a.owner}/{a.title}",
                                                           "licenses": [{"name": "other"}]}), encoding="utf-8")
    print(f"{rows:,} rows in {k - a.start} parts -> {out} "
          f"({sum(p.stat().st_size for p in out.rglob('*') if p.is_file()) / 1e9:.2f} GB)")


if __name__ == "__main__":
    main()
